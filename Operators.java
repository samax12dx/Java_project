class Main {
    public static void main(String[] args) {
        int num1=20;
        int num2=6;
        System.out.println("20+6= " +(num1+num2)) ;
        System.out.println("20-6= " +(num1-num2)) ;
        System.out.println("20/6= " +(num1/num2)) ;
        System.out.println("20*6= " +(num1*num2)) ;
        System.out.println("20%6= " +(num1%num2)) ;
    }
}